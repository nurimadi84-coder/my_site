def system_prompt() -> str:
    return SYSTEM.replace("{phone}", shop_phone_display())


def build_system_prompt(extra_context: str = "") -> str:
    base = system_prompt()
    extra = (extra_context or "").strip()
    if extra:
        return base + "\n\n" + extra
    return base
